import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {ui} from './ui';

for(const locale of ['zh-TW','en'] as const)test(`${locale}: precise navigation and coordinate inspection preserve the run`,async({page})=>{
  const t=(key:string)=>ui(key,locale);const errors:string[]=[];let searches=0;
  page.on('pageerror',error=>errors.push(error.message));page.on('request',request=>{if(request.postData()?.includes('"action":"race"'))searches++;});
  await page.addInitScript(l=>localStorage.setItem('arena.locale.v1',l),locale);
  await page.goto('/');await page.getByRole('button',{name:t('Enter laboratory'),exact:true}).click();
  await expect(page.getByRole('button',{name:t('Run experiment')})).toBeEnabled({timeout:60000});
  await page.getByRole('button',{name:t('Run experiment')}).click();
  const timeline=page.getByLabel(t('Event timeline'));await expect(timeline).toBeVisible();
  await page.getByLabel(t('End'),{exact:true}).click();
  const beforeDownload=page.waitForEvent('download');await page.getByRole('button',{name:t('Export Run')}).click();
  const before=readFileSync((await(await beforeDownload).path())!,'utf8');
  await page.getByText(t('Precise navigation and keyboard shortcuts'),{exact:true}).click();
  await page.getByLabel(t('Clock position'),{exact:true}).fill('13');await page.getByRole('button',{name:t('Jump to position'),exact:true}).click();
  await expect(timeline).toHaveValue('13');
  await page.getByLabel(t('Clock position'),{exact:true}).focus();await page.keyboard.press('Home');await expect(timeline).toHaveValue('13');
  await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();});
  await page.keyboard.press('Home');await expect(timeline).toHaveValue('0');
  await page.keyboard.press('ArrowRight');await expect(timeline).toHaveValue('1');
  await page.keyboard.press('ArrowLeft');await expect(timeline).toHaveValue('0');
  await page.keyboard.press('Shift+ArrowRight');expect(Number(await timeline.inputValue())).toBeGreaterThan(0);
  await page.keyboard.press('End');expect(await timeline.inputValue()).toBe(await timeline.getAttribute('max'));
  await page.getByRole('button',{name:t('INSPECT'),exact:true}).click();
  await page.getByLabel(t('Column (x)'),{exact:true}).fill('3');await page.getByLabel(t('Row (y)'),{exact:true}).fill('4');
  await page.getByRole('button',{name:t('Inspect coordinates'),exact:true}).click();
  await expect(page.locator('.inspector h2')).toContainText('3, 4');await expect(page.locator('.node-details')).toBeVisible();
  await page.getByLabel(t('Column (x)'),{exact:true}).fill('32');await page.getByRole('button',{name:t('Inspect coordinates'),exact:true}).click();
  await expect(page.locator('.inspector h2')).toContainText('3, 4');
  await page.getByRole('button',{name:t('BUILD'),exact:true}).click();
  await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();});await page.keyboard.press('Home');
  expect(await timeline.inputValue()).toBe(await timeline.getAttribute('max'));
  const afterDownload=page.waitForEvent('download');await page.getByRole('button',{name:t('Export Run')}).click();
  expect(readFileSync((await(await afterDownload).path())!,'utf8')).toBe(before);expect(searches).toBe(1);expect(errors).toEqual([]);
});

test('rerunning the heuristic laboratory keeps all five configurations and hashes',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('arena.locale.v1','zh-TW'));await page.goto('/');
  await page.getByRole('button',{name:ui('Enter laboratory'),exact:true}).click();
  await page.locator('.lab-controls>summary').click();
  await expect(page.getByRole('button',{name:ui('Compare four heuristics'),exact:true})).toBeEnabled({timeout:60000});
  const race=()=>page.waitForResponse(r=>r.url().endsWith('/api/arena')&&r.request().postData()?.includes('"action":"race"')===true);
  const firstResponse=race();await page.getByRole('button',{name:ui('Compare four heuristics'),exact:true}).click();const first=await(await firstResponse).json();
  await expect(page.locator('.race-panels canvas')).toHaveCount(5);
  await expect(page.getByRole('button',{name:ui('Run experiment')})).toBeEnabled();
  const secondResponse=race();await page.getByRole('button',{name:ui('Run experiment')}).click();const second=await(await secondResponse).json();
  await expect(page.locator('.race-panels canvas')).toHaveCount(5);
  expect(second.logs.map((l:{config:unknown})=>l.config)).toEqual(first.logs.map((l:{config:unknown})=>l.config));
  expect(second.logs.map((l:{canonical_hash:string})=>l.canonical_hash)).toEqual(first.logs.map((l:{canonical_hash:string})=>l.canonical_hash));
  await expect(page.getByRole('button',{name:ui('Run experiment')})).toBeEnabled();
  await page.getByRole('button',{name:ui('Show configuration'),exact:true}).click();
  await page.getByRole('button',{name:ui('Next seed'),exact:true}).click();
  await expect(page.getByRole('button',{name:ui('Run experiment')})).toBeEnabled();
  const thirdResponse=race();await page.getByRole('button',{name:ui('Run experiment')}).click();const third=await(await thirdResponse).json();
  expect(third.logs.map((l:{config:unknown})=>l.config)).toEqual(first.logs.map((l:{config:unknown})=>l.config));
  expect(third.logs[0].map_config.seed).toBe(first.logs[0].map_config.seed+1);
});
